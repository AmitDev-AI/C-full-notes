/* Build assets/search-index.js from the HTML pages.
   Run with:  node tools/build-search-index.js
   No dependencies. Re-run it after editing page content. */
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");

const GROUPS = [
  { name: "Tutorial", files: [
    "index.html", "c-intro.html", "c-setup.html", "c-syntax.html", "c-output.html",
    "c-comments.html", "c-variables.html", "c-datatypes.html", "c-constants.html",
    "c-operators.html", "c-conditions.html", "c-switch.html", "c-loops.html",
    "c-arrays.html", "c-strings.html", "c-input.html"
  ]},
  { name: "Advanced", files: [
    "c-functions.html", "c-pointers.html", "c-structures.html", "c-unions-enums.html",
    "c-files.html", "c-memory.html", "c-preprocessor.html"
  ]},
  { name: "Practice", files: ["c-exercises.html", "c-quiz.html", "c-certificate.html"] },
  { name: "Reference", files: ["c-reference.html", "c-cheatsheet.html", "c-glossary.html", "c-examples.html"] },
  { name: "Tools", files: ["tryit.html", "search.html", "bookmarks.html"] }
];

const groupFor = {};
GROUPS.forEach(g => g.files.forEach(f => { groupFor[f] = g.name; }));

const ENTITIES = {
  amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ",
  mdash: "—", ndash: "–", hellip: "…", rarr: "→", larr: "←",
  middot: "·", copy: "©", times: "×", divide: "÷", deg: "°",
  le: "≤", ge: "≥", ne: "≠", laquo: "«", raquo: "»"
};

function decode(s) {
  return s
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(parseInt(d, 10)))
    .replace(/&([a-z]+);/gi, (m, name) => {
      const key = name.toLowerCase();
      return Object.prototype.hasOwnProperty.call(ENTITIES, key) ? ENTITIES[key] : m;
    });
}

function text(html) {
  return decode(
    html
      .replace(/<script[\s\S]*?<\/script>/gi, " ")
      .replace(/<style[\s\S]*?<\/style>/gi, " ")
      .replace(/<pre[\s\S]*?<\/pre>/gi, " ")
      .replace(/<[^>]+>/g, " ")
  ).replace(/\s+/g, " ").trim();
}

function slug(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
}

function parsePage(file) {
  const html = fs.readFileSync(path.join(ROOT, file), "utf8");
  const titleMatch = html.match(/<title>([\s\S]*?)<\/title>/i);
  const title = titleMatch ? decode(titleMatch[1]).replace(/\s*—\s*C Notes\s*$/, "").trim() : file;
  const mainMatch = html.match(/<main[^>]*>([\s\S]*?)<\/main>/i);
  if (!mainMatch) return null;
  const main = mainMatch[1];
  const h2 = /<h2([^>]*)>([\s\S]*?)<\/h2>/gi;
  const marks = [];
  let m;
  while ((m = h2.exec(main))) {
    const attrs = m[1] || "";
    const heading = text(m[2]);
    const idMatch = attrs.match(/\bid\s*=\s*["']([^"']+)["']/i);
    marks.push({ index: m.index, end: h2.lastIndex, heading, id: idMatch ? idMatch[1] : slug(heading) });
  }

  const sections = [];
  const intro = text(main.slice(0, marks.length ? marks[0].index : main.length));
  if (intro) sections.push({ id: "", h: title, text: intro.slice(0, 1200) });

  marks.forEach((mark, i) => {
    const body = text(main.slice(mark.end, i + 1 < marks.length ? marks[i + 1].index : main.length));
    if (!body) return;
    sections.push({ id: mark.id, h: mark.heading, text: body.slice(0, 1200) });
  });

  return {
    page: file,
    title,
    group: groupFor[file] || "Other",
    url: file,
    sections
  };
}

const files = [];
GROUPS.forEach(g => g.files.forEach(f => files.push(f)));
["404.html"].forEach(f => { if (fs.existsSync(path.join(ROOT, f))) files.push(f); });

const index = [];
files.forEach(file => {
  if (!fs.existsSync(path.join(ROOT, file))) return;
  try {
    const entry = parsePage(file);
    if (entry && entry.sections.length) index.push(entry);
  } catch (err) {
    console.warn("Skipping", file, err.message);
  }
});

const out = "/* Generated by tools/build-search-index.js — do not edit by hand.\n" +
            "   Re-run the script after changing page content. */\n" +
            "window.CNOTES_INDEX = " + JSON.stringify(index) + ";\n";
fs.writeFileSync(path.join(ROOT, "assets", "search-index.js"), out, "utf8");
const size = fs.statSync(path.join(ROOT, "assets", "search-index.js")).size;
console.log("Indexed " + index.length + " pages, " +
  index.reduce((n, p) => n + p.sections.length, 0) + " sections, " +
  Math.round(size / 1024) + " KB.");
